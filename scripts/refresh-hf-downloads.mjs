// Generates content/generated/hf-downloads.json: the AetherArt page's Hugging Face download
// counts (aetherart:hf-downloads). Weekly via metrics-refresh.yml, or: node scripts/refresh-hf-downloads.mjs
// HF's `downloads` is a rolling 30-day count, so the old hand-typed "124 · 14 · 0" (2026-07-30) went
// stale within weeks; it is now a generated artifact.
//
//  - R3: any network/HTTP (401/403/429/5xx)/parse/shape error exits non-zero with `::error::`,
//    and the existing snapshot is NOT touched.
//  - Fallback: the site build never calls Hugging Face; it renders the last COMMITTED snapshot and
//    the page row always says "as of <fetchedAt>", so an unreachable API shows an honestly dated
//    figure, never a fresh-looking stale one.
//  - Env (for hermetic tests): HF_API_URL, HF_SNAPSHOT_PATH, HF_FETCH_DATE, HF_TOKEN (optional).

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const HF_AUTHOR = "gauravgandhi2411";
const DEFAULT_API_URL = `https://huggingface.co/api/models?author=${HF_AUTHOR}`;
// Display order of the page row ("ukiyo-e SDXL · ukiyo-e SD 2.1 · Pattachitra SDXL").
const EXPECTED_MODELS = [
  "aetherart-ukiyo-sdxl",
  "aetherart-ukiyo-sd21",
  "aetherart-pattachitra-sdxl",
];
const FETCH_TIMEOUT_MS = 20_000;

const apiUrl = process.env.HF_API_URL ?? DEFAULT_API_URL;
const snapshotPath =
  process.env.HF_SNAPSHOT_PATH ?? join(ROOT, "content", "generated", "hf-downloads.json");
const fetchedAt = process.env.HF_FETCH_DATE ?? new Date().toISOString().slice(0, 10);

function fail(message) {
  console.error(`::error::hf-downloads: ${message}`);
  console.error(`hf-downloads: snapshot left unchanged at ${snapshotPath}`);
  process.exit(1);
}

let res;
try {
  const headers = { Accept: "application/json" };
  if (process.env.HF_TOKEN) headers.Authorization = `Bearer ${process.env.HF_TOKEN}`;
  res = await fetch(apiUrl, { headers, signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
} catch (err) {
  fail(`could not reach ${apiUrl}: ${err.cause?.code ?? err.message}`);
}
if (!res.ok) {
  const kind =
    res.status === 401 || res.status === 403
      ? "auth error"
      : res.status === 429
        ? "rate limited"
        : "HTTP error";
  fail(`${kind}: ${apiUrl} returned HTTP ${res.status}`);
}

let body;
try {
  body = await res.json();
} catch {
  fail(`${apiUrl} did not return valid JSON`);
}
if (!Array.isArray(body)) fail(`unexpected shape: expected a JSON array of models from ${apiUrl}`);

const models = EXPECTED_MODELS.map((name) => {
  const entry = body.find((m) => m?.id === `${HF_AUTHOR}/${name}`);
  if (!entry) fail(`expected model ${HF_AUTHOR}/${name} is missing from the API response`);
  const { downloads } = entry;
  if (!Number.isInteger(downloads) || downloads < 0) {
    fail(`${name}: "downloads" is ${JSON.stringify(downloads)}, expected a non-negative integer`);
  }
  return { id: name, downloads };
});

const snapshot = {
  _readme:
    "GENERATED by scripts/refresh-hf-downloads.mjs (weekly, metrics-refresh.yml). Do not hand-edit. `downloads` is Hugging Face's rolling last-30-days count as of `fetchedAt`, not cumulative.",
  source: DEFAULT_API_URL,
  fetchedAt,
  window: "last 30 days",
  models,
};
writeFileSync(snapshotPath, JSON.stringify(snapshot, null, 2) + "\n");
console.log(
  `hf-downloads: wrote ${snapshotPath} (${models.map((m) => `${m.id}=${m.downloads}`).join(", ")}; as of ${fetchedAt})`
);
